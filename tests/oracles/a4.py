"""The tetrahedral group A4, a test symmetry with outer multiplicity: 3 x 3 = 1 + 1' + 1'' + 3 + 3.

Labels 0, 1, 2, 3 stand for the irreps 1, 1', 1'', 3; 1' and 1'' are dual to each other. The
group is generated by s = diag(1, -1, -1) and the cyclic shift t, (t x)_i = x_(i+1), on the 3,
and by s = 1, t = w^k on the one-dimensional irrep k (w = exp(2 pi i / 3)). CG arrays are closed
forms in that basis; F and R are computed from them.
"""
import itertools
from dataclasses import dataclass
from functools import lru_cache

import numpy as np

from tnkit.symmetry import Symmetry, f_from_cg, r_from_cg

W = np.exp(2j * np.pi / 3)
_GENERATORS = {k: (np.eye(1), W ** k * np.eye(1)) for k in range(3)}
_GENERATORS[3] = (np.diag([1.0, -1.0, -1.0]), np.roll(np.eye(3), 1, axis=1))


@lru_cache(maxsize=None)
def _cg(a, b, c):
    one = (a < 3) + (b < 3)                          # how many one-dimensional factors
    n = dict(A4().fusions(a, b)).get(c, 0)
    x = np.zeros((A4().dim(a), A4().dim(b), A4().dim(c), n), complex)
    if n == 0:
        pass
    elif one == 2:
        x[0, 0, 0, 0] = 1
    elif one == 1:                                   # k x 3 or 3 x k -> 3: diag(w^(-k y))
        k = a if a < 3 else b
        phase = W ** (-k * np.arange(3))
        if a < 3:
            x[0, range(3), range(3), 0] = phase
        else:
            x[range(3), 0, range(3), 0] = phase
    elif c < 3:                                      # 3 x 3 -> k: diag(w^(k x)) / sqrt 3
        x[range(3), range(3), 0, 0] = W ** (c * np.arange(3)) / np.sqrt(3)
    else:                                            # 3 x 3 -> 3: symmetric, then antisymmetric
        for p in itertools.permutations(range(3)):
            x[p + (0,)] = 1 / np.sqrt(2)
            x[p + (1,)] = np.linalg.det(np.eye(3)[list(p)]) / np.sqrt(2)
    x.flags.writeable = False
    return x


@dataclass(frozen=True)
class A4(Symmetry):
    fusion = "generic"

    def unit(self):
        return 0

    def dual(self, a):
        return (0, 2, 1, 3)[a]

    def label(self, a):
        if isinstance(a, (bool, np.bool_)) or int(a) != a or not 0 <= int(a) <= 3:
            raise ValueError(f"A4 labels are 0..3, got {a!r}")
        return int(a)

    def dim(self, a):
        return 3 if a == 3 else 1

    def fusions(self, a, b):
        if a < 3 and b < 3:
            return (((a + b) % 3, 1),)
        if a < 3 or b < 3:
            return ((3, 1),)
        return ((0, 1), (1, 1), (2, 1), (3, 2))

    def fuse(self, a, b):
        (c, n), *rest = self.fusions(a, b)
        if rest or n > 1:
            raise ValueError(f"A4: {a} x {b} has several outcomes; use fusions()")
        return c

    def cg(self, a, b, c):
        return _cg(a, b, c)

    @lru_cache(maxsize=None)
    def F(self, a, b, c, d, e, f):
        x = f_from_cg(self, a, b, c, d, e, f)
        x.flags.writeable = False
        return x

    @lru_cache(maxsize=None)
    def R(self, a, b, c):
        x = r_from_cg(self, a, b, c)
        x.flags.writeable = False
        return x

    def rep(self, a, word):
        """The matrix of irrep `a` at the group element `word` (see `elements`)."""
        m = np.eye(self.dim(a), dtype=complex)
        for g in word:
            m = _GENERATORS[a][g] @ m
        return m


@lru_cache(maxsize=None)
def elements():
    """The 12 group elements as words in the generators (0 = s, 1 = t), found on the 3."""
    found = {(): np.eye(3)}
    frontier = [()]
    while frontier:
        nxt = []
        for word in frontier:
            for g in (0, 1):
                m = _GENERATORS[3][g] @ found[word]
                if not any(np.allclose(m, y) for y in found.values()):
                    found[word + (g,)] = m
                    nxt.append(word + (g,))
        frontier = nxt
    return tuple(found)



class A4RotatedCopies(A4):
    """The two copies of 3 in 3 x 3 rotated by a complex unitary, F and R recomputed: an equally
    valid gauge in which R(3, 3, 3) is not diagonal."""
    U = np.array([[0.6, 0.8j], [0.8j, 0.6]]) @ np.diag([1, np.exp(0.4j)])

    def cg(self, a, b, c):
        x = super().cg(a, b, c)
        return x @ self.U if (a, b, c) == (3, 3, 3) else x


class A4RephasedSinglet(A4):
    """cg(1', 1'', 1) times -1, F and R recomputed: an equally valid gauge in which the cups of
    1' and 1'' differ and kappa of 1' is -1."""

    def cg(self, a, b, c):
        x = super().cg(a, b, c)
        return -x if (a, b, c) == (1, 2, 0) else x


class A4ComplexBasis(A4):
    """A4 with its 3 in the basis U e_k, U a fixed complex unitary: same F and R, complex cup."""
    U = np.linalg.qr(np.arange(9).reshape(3, 3) + 1j * np.cos(np.arange(9)).reshape(3, 3)
                     + np.eye(3))[0]

    def _u(self, a):
        return self.U if a == 3 else np.eye(1)

    def cg(self, a, b, c):
        return np.einsum("xX,yY,XYZm,zZ->xyzm", self._u(a), self._u(b), super().cg(a, b, c),
                         self._u(c).conj())

    def rep(self, a, g):
        return self._u(a) @ super().rep(a, g) @ self._u(a).conj().T
